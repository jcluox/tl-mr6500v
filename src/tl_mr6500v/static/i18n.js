const STORAGE_KEY = "tl6500v_lang";

function detectLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved in LANGUAGES) return saved;
  } catch {} // If localStorage is unavailable (private mode and so on), use the browser language
  for (const tag of navigator.languages ?? [navigator.language]) {
    const l = (tag || "").toLowerCase();
    if (l.startsWith("zh")) return /tw|hk|mo|hant/.test(l) ? "zh-TW" : "zh-CN";
    if (l.startsWith("ja")) return "ja";
    if (l.startsWith("en")) return "en";
  }
  return "en";
}

let currentLang = detectLang();

function t(key, vars = {}) {
  const text = STRINGS[currentLang]?.[key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? "");
}

const locale = () => LANGUAGES[currentLang].locale;

// Apply to the static markup: data-i18n replaces the text content
function applyI18n() {
  document.documentElement.lang = LANGUAGES[currentLang].htmlLang;
  for (const node of document.querySelectorAll("[data-i18n]")) node.textContent = t(node.dataset.i18n);
  for (const node of document.querySelectorAll("[data-i18n-label]")) {
    node.setAttribute("aria-label", t(node.dataset.i18nLabel));
  }
  for (const select of document.querySelectorAll(".lang-select")) {
    if (!select.options.length) {
      for (const [code, { label }] of Object.entries(LANGUAGES)) select.add(new Option(label, code));
    }
    select.value = currentLang;
  }
}

function setLang(code) {
  if (!(code in LANGUAGES)) return;
  currentLang = code;
  try {
    localStorage.setItem(STORAGE_KEY, code);
  } catch {}
  applyI18n();
}
